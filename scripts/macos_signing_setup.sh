#!/usr/bin/env bash
# One-time setup of a self-signed code-signing identity for macOS builds.
# macOS privacy grants (microphone, etc.) are bound to the app's designated
# requirement; ad-hoc signatures pin it to the binary hash, so every build
# is a new app. A certificate-based identity keeps the grant across builds.
set -euo pipefail

IDENTITY="Manent Signing"
DIR="$HOME/.manent/macos-signing"
REPO="$(cd "$(dirname "$0")/.." && pwd)"
XCCONFIG="$REPO/macos/Runner/Configs/Signing.local.xcconfig"
KEYCHAIN="$HOME/Library/Keychains/login.keychain-db"

write_xcconfig() {
  cat > "$XCCONFIG" <<EOF
// Generated by scripts/macos_signing_setup.sh, not tracked by git
CODE_SIGN_IDENTITY = $IDENTITY
CODE_SIGN_STYLE = Manual
EOF
  echo "Wrote $XCCONFIG"
}

if security find-identity -v -p codesigning | grep -q "\"$IDENTITY\""; then
  echo "Identity \"$IDENTITY\" already present in the keychain"
  write_xcconfig
  exit 0
fi

OPENSSL="${OPENSSL:-$(command -v openssl)}"
if ! "$OPENSSL" version | grep -q '^OpenSSL 3'; then
  echo "Need OpenSSL 3 (brew install openssl); found: $("$OPENSSL" version)" >&2
  exit 1
fi

mkdir -p "$DIR"
chmod 700 "$DIR"
cd "$DIR"

if [[ ! -f cert.pem || ! -f key.pem ]]; then
  cat > openssl.cnf <<EOF
[ req ]
distinguished_name = dn
x509_extensions = ext
prompt = no
[ dn ]
CN = $IDENTITY
[ ext ]
keyUsage = critical,digitalSignature
extendedKeyUsage = critical,codeSigning
basicConstraints = critical,CA:false
subjectKeyIdentifier = hash
EOF
  "$OPENSSL" req -x509 -newkey rsa:2048 -nodes -sha256 -days 3650 \
    -keyout key.pem -out cert.pem -config openssl.cnf
  chmod 600 key.pem
  echo "Created certificate in $DIR"
else
  echo "Reusing existing certificate in $DIR"
fi

# OpenSSL 3 defaults to a PKCS#12 MAC that `security import` rejects; the
# password only protects this transient bundle, key.pem is the real secret
P12_PASS="manent"
"$OPENSSL" pkcs12 -export -legacy -inkey key.pem -in cert.pem \
  -name "$IDENTITY" -passout "pass:$P12_PASS" -out identity.p12
chmod 600 identity.p12

security import identity.p12 -k "$KEYCHAIN" -P "$P12_PASS" \
  -T /usr/bin/codesign -T /usr/bin/security

# Without explicit trust the identity is invisible to codesign; this prompts once
echo "Trusting the certificate for code signing (login password prompt follows)"
security add-trusted-cert -p codeSign -k "$KEYCHAIN" cert.pem

echo
security find-identity -v -p codesigning | grep "$IDENTITY" \
  || { echo "Identity not found after import" >&2; exit 1; }

write_xcconfig
echo "Done. Back up $DIR: losing it means one more permission re-prompt for every user."
