#!/bin/bash
# Precompiles the Metal shaders into darwin/Resources/<platform>/default.metallib.
# Usage: build_metal_lib.sh ios|macos   (run generate_metal_embed.sh first)

set -e

PLATFORM="$1"
case "$PLATFORM" in
  ios)   SDK=iphoneos; STD=ios-metal2.3 ;;
  macos) SDK=macosx;   STD=macos-metal2.3 ;;
  *) echo "Usage: $0 ios|macos"; exit 1 ;;
esac

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DARWIN_DIR="$(dirname "$SCRIPT_DIR")"
CLASSES_DIR="$DARWIN_DIR/Classes"
METAL_SOURCE="$DARWIN_DIR/autogenerated/ggml-metal-embed.metal"
OUTPUT_DIR="$DARWIN_DIR/Resources/$PLATFORM"

if [ ! -f "$METAL_SOURCE" ]; then
    echo "Error: $METAL_SOURCE not found, run generate_metal_embed.sh first"
    exit 1
fi

mkdir -p "$OUTPUT_DIR"

xcrun -sdk "$SDK" metal \
    -std="$STD" \
    -O3 \
    -I"$CLASSES_DIR/whisper/ggml/include" \
    -I"$CLASSES_DIR/whisper/ggml/src" \
    -I"$CLASSES_DIR/whisper/ggml/src/ggml-metal" \
    -c "$METAL_SOURCE" \
    -o "$OUTPUT_DIR/ggml-metal.air"

xcrun -sdk "$SDK" metallib \
    "$OUTPUT_DIR/ggml-metal.air" \
    -o "$OUTPUT_DIR/default.metallib"

rm -f "$OUTPUT_DIR/ggml-metal.air"

echo "Built $OUTPUT_DIR/default.metallib"
ls -lh "$OUTPUT_DIR/default.metallib"
